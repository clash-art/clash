/**
 * Regenerates src/generated/cloud-plugin-validators.js: Ajv standalone
 * validators for every Generator schema the hosted plugin catalog exposes.
 * workerd forbids Ajv's runtime compilation, so a schema missing here fails
 * at its first validation in the Worker. The freshness test keeps it current.
 *
 *   pnpm --dir apps/api-cf generate:cloud-plugin-validators
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  generatorDefinitionSchemas,
  renderPrecompiledGeneratorValidatorModule,
} from "@clash/shared-runtime/generator-validator-codegen";
import { buildCloudPluginCatalog } from "../src/services/cloud-plugin-packages";

export const CLOUD_PLUGIN_VALIDATORS_PATH = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src/generated/cloud-plugin-validators.js",
);

const HEADER = `// Generated by apps/api-cf/scripts/generate-cloud-plugin-validators.ts. Do not edit.
// Ajv standalone validators for the cloud plugin catalog, keyed by generatorSchemaKey.
/* eslint-disable */`;

export function renderCloudPluginValidators(): string {
  return renderPrecompiledGeneratorValidatorModule(
    generatorDefinitionSchemas(buildCloudPluginCatalog().generatorDefinitions()),
    { exportName: "cloudPluginValidators", header: HEADER },
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  writeFileSync(CLOUD_PLUGIN_VALIDATORS_PATH, renderCloudPluginValidators());
  console.log(`Wrote ${CLOUD_PLUGIN_VALIDATORS_PATH}`);
}
